def kernel_multisrc_diffuse_simple(pos1, pos2, wave_num, src_idx):
    """
    
    src_idx : ndarray of shape (num_src, num_pos) with boolean values
    """
    kernel_vals = ki.kernel_diffuse(pos1, pos2, wave_num)

    num_freq = wave_num.shape[0]
    num_src = src_idx.shape[0]

    num_pos1 = pos1.shape[0]
    num_pos2 = pos2.shape[0]

    if not np.all(src_idx):
        raise NotImplementedError("Not implemented for sources that were not measured at all positions")
    num_params1 = num_pos1 * num_src
    num_params2 = num_pos2 * num_src

    full_kernel_matrix = np.zeros((num_freq, num_params1, num_params2), dtype=np.complex128)

    for m in range(num_pos1):
        for n in range(num_pos2):
            full_kernel_matrix[:, m*num_src:(m+1)*num_src, n*num_src:(n+1)*num_src] = np.eye(num_src)[None,:,:] * kernel_vals[:,m:m+1,n:n+1]
    return full_kernel_matrix

