def kernel_multisrc_directional(pos1, pos2, wave_num, src_idx1, src_idx2, directions, beta):
    """Kernel for joint estimation of a multisource sound field with non-identity source weighting and directional weighting.

    Uses the von-mises fisher distribution to model the directional weighting, which gives a closed form solution for the kernel.
    This means that only a single direction can be promoted for each source. 

    Parameters
    ----------
    pos1 : ndarray of shape (num_pos1, 3)
    pos2 : ndarray of shape (num_pos2, 3)
    wave_num : ndarray of shape (num_freq)
        wave numbers for the frequencies of interest, defined as 2*pi*f/c
    src_idx1 : ndarray of shape (num_src, num_pos1) with boolean values
        For each position m in pos1, the value in src_idx1[s,m] indicates whether the source s was measured there
    src_idx2 : ndarray of shape (num_src, num_pos2) with boolean values
        For each position n in pos2, the value in src_idx2[s,n] indicates whether the source s was measured there
    src_weighting : ndarray of shape (num_freq, num_src, num_src)
        The weighting of the sources for each frequency. This is in some sense a measure of 
        similarity between the sound fields generated by the sources.
    directions : ndarray of shape (num_src, 3)
        The directions of the sources.
    beta : non-negative ndarray of shape (num_src,)
        The concentration parameter for the von-mises fisher distribution.

    Returns
    -------
    full_kernel_matrix : ndarray of shape (num_freq, num_params1, num_params2)
        The kernel matrix for the given positions and sources. num_params1 and num_params2 are the number of parameters
        which can be calculated as sum(src_idx1) and sum(src_idx2) respectively. This should be exactly the total
        number of measurements in total. 
    """
    return kernel_multisrc(pos1, pos2, wave_num, src_idx1, src_idx2, base_kernel=ki.kernel_directional, base_kernel_args=[directions, beta])

